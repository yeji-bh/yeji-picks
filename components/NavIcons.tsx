export function NavItem({
  href,
  icon,
  label,
  onClick,
}: {
  href?: string;
  icon: React.ReactNode;
  label: string;
  onClick?: () => void;
}) {
  const className =
    "flex cursor-pointer items-center gap-1 whitespace-nowrap hover:text-neutral-900";

  if (onClick) {
    return (
      <button type="button" onClick={onClick} className={className} title={label}>
        {icon}
        <span>{label}</span>
      </button>
    );
  }

  return (
    <Link href={href!} className={className} title={label}>
      {icon}
      <span>{label}</span>
    </Link>
  );
}
